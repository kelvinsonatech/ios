import type { ProtocolAdapter } from "../types";
import { AdapterResponseError, ConfigReader, fileArtifact, requireRemoteId, resolveExpiry, ValuesBuilder } from "./base";

/**
 * WireGuard. The node generates the key pair and peer; the website only presents it.
 * Expected `config`:
 * {
 *   config_text?: "[Interface]...[Peer]...",          // authoritative when present
 *   interface?: { address, dns?, private_key },
 *   peer?: { public_key, preshared_key?, endpoint, allowed_ips?, persistent_keepalive? }
 * }
 */
const KEY = /^[A-Za-z0-9+/]{42,43}=?$/;

export const wireguardAdapter: ProtocolAdapter = {
  key: "wireguard",
  label: "WireGuard",
  description: "WireGuard peer generated by the node. Returns a .conf file and QR code.",
  inputGuards: {},
  requiredInputs: [],
  supportsRenew: true,
  outputFields: [
    { key: "address", label: "Client address", kind: "text", sensitive: false, copyable: true },
    { key: "dns", label: "DNS", kind: "text", sensitive: false, copyable: true },
    { key: "public_key", label: "Server public key", kind: "text", sensitive: false, copyable: true },
    { key: "private_key", label: "Client private key", kind: "secret", sensitive: true, copyable: true },
    { key: "preshared_key", label: "Preshared key", kind: "secret", sensitive: true, copyable: true, hidden: true },
    { key: "endpoint", label: "Endpoint", kind: "text", sensitive: false, copyable: true },
    { key: "allowed_ips", label: "Allowed IPs", kind: "text", sensitive: false, copyable: true },
    { key: "persistent_keepalive", label: "Persistent keepalive", kind: "text", sensitive: false, copyable: false },
  ],
  defaultFields: [{ key: "duration", label: "Duration", type: "duration", required: true, options: [], validation: {} }],

  buildSpec(input, ctx) {
    return {
      protocol: ctx.serverProtocol.nodeIdentifier ?? ctx.protocol.slug,
      username: input.username,
      durationDays: input.durationDays,
      options: input.options,
    };
  },

  parseAccount(account, _ctx, input) {
    const cfg = new ConfigReader(account.config);
    const iface = cfg.obj("interface");
    const peer = cfg.obj("peer");
    const privateKey = iface.str("private_key", 64);
    const address = iface.str("address", 128);
    const dns = iface.str("dns", 256);
    const publicKey = peer.str("public_key", 64);
    const psk = peer.str("preshared_key", 64);
    const endpoint = peer.str("endpoint", 300);
    const allowedIps = peer.str("allowed_ips", 512) ?? "0.0.0.0/0, ::/0";
    const keepalive = peer.int("persistent_keepalive");

    for (const [name, k] of [["private key", privateKey], ["public key", publicKey], ["preshared key", psk]] as const) {
      if (k && !KEY.test(k)) throw new AdapterResponseError(`Server returned an invalid WireGuard ${name}.`);
    }

    let text = cfg.text("config_text", 8192);
    if (text && !(/\[Interface\]/.test(text) && /\[Peer\]/.test(text))) {
      throw new AdapterResponseError("Server returned an invalid WireGuard configuration.");
    }
    if (!text) {
      if (!privateKey || !address || !publicKey || !endpoint) {
        throw new AdapterResponseError("Server did not return a WireGuard configuration.");
      }
      text = [
        "[Interface]",
        `PrivateKey = ${privateKey}`,
        `Address = ${address}`,
        ...(dns ? [`DNS = ${dns}`] : []),
        "",
        "[Peer]",
        `PublicKey = ${publicKey}`,
        ...(psk ? [`PresharedKey = ${psk}`] : []),
        `Endpoint = ${endpoint}`,
        `AllowedIPs = ${allowedIps}`,
        ...(keepalive ? [`PersistentKeepalive = ${keepalive}`] : []),
        "",
      ].join("\n");
    }

    const v = new ValuesBuilder()
      .set("address", address)
      .set("dns", dns)
      .set("public_key", publicKey)
      .set("private_key", privateKey, true)
      .set("preshared_key", psk, true)
      .set("endpoint", endpoint)
      .set("allowed_ips", allowedIps)
      .set("persistent_keepalive", keepalive);

    const name = account.username ?? input.username ?? account.accountId;
    return {
      remoteAccountId: requireRemoteId(account),
      username: account.username ?? input.username,
      expiresAt: resolveExpiry(account, input),
      values: v.values,
      artifacts: [
        fileArtifact({
          key: "config",
          label: "WireGuard configuration",
          content: text,
          filename: `wg-${name}.conf`,
          mimeType: "text/plain",
          qr: true,
          sensitive: true,
        }),
      ],
    };
  },
};
