/**
 * Provisioning lifecycle (docs/05-provisioning.md):
 *
 *   request → validate → rate-limit → check server/protocol/capacity → pending account + request
 *   → queue → worker sends to node → validate response → store safe metadata → active
 *                                  ↘ definite failure → failed (+ capacity released)
 *                                  ↘ uncertain (timeout after sending) → look up by request id
 *                                    before ANY retry, so a slow node never yields two accounts.
 */

export class ProvisioningError extends Error {
  constructor(
    readonly code:
      | "PROTOCOL_NOT_FOUND"
      | "SERVER_NOT_FOUND"
      | "VALIDATION_FAILED"
      | "RATE_LIMITED"
      | "SERVER_UNAVAILABLE"
      | "PROTOCOL_UNAVAILABLE"
      | "CAPACITY_REACHED"
      | "QUOTA_REACHED"
      | "IDEMPOTENCY_CONFLICT"
      | "INVALID_IDEMPOTENCY_KEY",
    message: string,
    readonly httpStatus: number,
    readonly fieldErrors?: Record<string, string[]>,
    readonly extra: {
      /** QUOTA_REACHED: when the creation quota of the server/protocol resets. */
      resetsAt?: Date;
      /** RATE_LIMITED: seconds until the client may try again. */
      retryAfterSeconds?: number;
      /** RATE_LIMITED: the per-day allowance per visitor and protocol, or the short burst limit. */
      limitScope?: "daily" | "burst";
    } = {},
  ) {
    super(message);
    this.name = "ProvisioningError";
  }

  get resetsAt() {
    return this.extra.resetsAt;
  }

  get retryAfterSeconds() {
    return this.extra.retryAfterSeconds;
  }

  get limitScope() {
    return this.extra.limitScope;
  }
}

export interface AccountRequestParams {
  serverId: string;
  protocolSlug: string;
  /** Raw form values keyed by protocol field key. */
  input: Record<string, unknown>;
  /** Random key generated by the client per form submission (double-click protection). */
  idempotencyKey: string;
  clientIp: string | null;
  /** Set for administrator-initiated test provisioning (skips public rate limits). */
  actor?: AuditActor;
}

export interface AccountRequestResult {
  requestId: string;
  claimToken: string;
  state: ProvisioningRequest["state"];
  replayed: boolean;
}

const IDEMPOTENCY_KEY = /^[A-Za-z0-9_-]{16,64}$/;

/** Deterministic per idempotency key, so a duplicate submission receives the same claim token. */
function claimTokenFor(idempotencyKey: string) {
  return hmacSha256Hex(env().IP_HASH_SECRET, `claim:${idempotencyKey}`);
}

function isUniqueViolation(e: unknown) {
  let cur: unknown = e;
  for (let i = 0; i < 4 && cur; i++) {
    if ((cur as { code?: string }).code === "23505") return true;
    cur = (cur as { cause?: unknown }).cause;
  }
  return false;
}

function zodFieldErrors(issues: { path: PropertyKey[]; message: string }[]) {
  const out: Record<string, string[]> = {};
  for (const i of issues) (out[String(i.path[0] ?? "_form")] ??= []).push(i.message);
  return out;
}

