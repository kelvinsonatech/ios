interface LoadedRequest {
  request: ProvisioningRequest;
  account: VpnAccount;
  server: Server;
  serverProtocol: ServerProtocol;
  def: ProtocolDefinition;
}

async function loadRequest(requestId: string): Promise<LoadedRequest | null> {
  const [row] = await db()
    .select({ request: provisioningRequests, account: vpnAccounts, server: servers, serverProtocol: serverProtocols })
    .from(provisioningRequests)
    .innerJoin(vpnAccounts, eq(vpnAccounts.id, provisioningRequests.accountId))
    .innerJoin(servers, eq(servers.id, provisioningRequests.serverId))
    .innerJoin(
      serverProtocols,
      and(eq(serverProtocols.serverId, provisioningRequests.serverId), eq(serverProtocols.protocolId, provisioningRequests.protocolId)),
    )
    .where(eq(provisioningRequests.id, requestId))
    .limit(1);
  if (!row) return null;
  const loaded = await getProtocolWithFields({ id: row.request.protocolId });
  if (!loaded) return null;
  return { ...row, def: loaded.definition };
}

function adapterContext(l: LoadedRequest): AdapterContext {
  return {
    protocol: l.def,
    server: { id: l.server.id, name: l.server.name, hostname: l.server.hostname, ipAddress: l.server.ipAddress },
    serverProtocol: {
      nodeIdentifier: l.serverProtocol.nodeIdentifier,
      ports: l.serverProtocol.ports,
      transports: l.serverProtocol.transports,
      metadata: l.serverProtocol.metadata,
    },
  };
}

function decryptInput(r: ProvisioningRequest): NormalizedAccountInput {
  if (!r.inputEncrypted) throw new Error("Request input is no longer available");
  return JSON.parse(decryptSecret(r.inputEncrypted, EncryptionContext.provisioningInput(r.id))) as NormalizedAccountInput;
}

const USER_MESSAGES: Record<string, string> = {
  USERNAME_TAKEN: "That username is already taken on this server. Please choose another one.",
  CAPACITY_REACHED: "This server is full. Please choose another server.",
  PROTOCOL_UNAVAILABLE: "This protocol is temporarily unavailable on this server.",
  VALIDATION_FAILED: "The server rejected the request. Please check your details and try again.",
  INVALID_NODE_RESPONSE: "The server returned an unexpected response. Please try another server.",
  OUTCOME_UNKNOWN: "We could not confirm your account with the server. Please try again later or choose another server.",
};
const DEFAULT_USER_MESSAGE = "We couldn't create your account right now. Please try again in a few minutes.";

/** Worker entry point for a `create` job. Safe to call more than once for the same request. */
export async function executeCreate(requestId: string): Promise<void> {
  const [claimed] = await db()
    .update(provisioningRequests)
    .set({ state: "in_flight", attempts: sql`${provisioningRequests.attempts} + 1`, startedAt: sql`coalesce(${provisioningRequests.startedAt}, now())` })
    .where(and(eq(provisioningRequests.id, requestId), eq(provisioningRequests.state, "queued"), eq(provisioningRequests.operation, "create")))
    .returning();
  if (!claimed) {
    const [r] = await db().select({ state: provisioningRequests.state }).from(provisioningRequests).where(eq(provisioningRequests.id, requestId));
    if (r?.state === "uncertain") await reconcile(requestId);
    return;
  }

  const l = await loadRequest(requestId);
  if (!l) return;
  const started = Date.now();
  let input: NormalizedAccountInput;
  try {
    input = decryptInput(l.request);
  } catch {
    await finalizeFailure(l, "INPUT_UNAVAILABLE", "Request input could not be read.", started);
    return;
  }
  const adapter = getAdapter(l.def.adapterKey);
  const ctx = adapterContext(l);

  let nodeAccount: NodeAccount;
  try {
    const spec = adapter.buildSpec(input, ctx);
    const { driver } = await getNodeDriver(l.server.id);
    nodeAccount = await driver.createAccount(spec, requestId);
  } catch (e) {
    if (e instanceof AdapterResponseError) {
      await finalizeFailure(l, "PROTOCOL_UNAVAILABLE", e.message, started);
      return;
    }
    if (isNodeError(e)) {
      await handleNodeFailure(l, e, started);
      return;
    }
    logger.error("unexpected provisioning error", { requestId, ...errorSummary(e) });
    await markUncertain(l, "UNEXPECTED", "Unexpected error while provisioning.");
    return;
  }
  await finalizeSuccess(l, nodeAccount, input, started);
}

async function handleNodeFailure(l: LoadedRequest, e: NodeError, started: number) {
  // REQUEST_IN_PROGRESS: the node is still processing an earlier attempt with this request id.
  if (e.delivery === "maybe" || e.code === "REQUEST_IN_PROGRESS") {
    await markUncertain(l, e.code, e.safeMessage);
    return;
  }
  if (e.delivery === "not_sent" && e.retryable && l.request.attempts < env().PROVISION_MAX_ATTEMPTS) {
    // The node never saw this request: safe to retry the create with backoff.
    await db()
      .update(provisioningRequests)
      .set({ state: "queued", errorCode: e.code, errorMessage: e.safeMessage })
      .where(and(eq(provisioningRequests.id, l.request.id), eq(provisioningRequests.state, "in_flight")));
    await enqueueProvisioning({ type: "create", requestId: l.request.id }, { delayMs: 2 ** l.request.attempts * 5_000 });
    return;
  }
  await finalizeFailure(l, e.code, e.safeMessage, started);
}

async function markUncertain(l: LoadedRequest, code: string, message: string) {
  await db()
    .update(provisioningRequests)
    .set({ state: "uncertain", errorCode: code, errorMessage: message })
    .where(eq(provisioningRequests.id, l.request.id));
  await logEvent({
    event: "account.uncertain",
    status: "info",
    level: "warning",
    serverId: l.server.id,
    protocolId: l.def.id,
    accountId: l.account.id,
    requestId: l.request.id,
    message: `Outcome unknown for ${l.def.name} request on ${l.server.name} (${code}); will look it up by request id before retrying.`,
  });
  await enqueueProvisioning({ type: "reconcile", requestId: l.request.id }, { delayMs: 10_000 });
}

const MAX_RECONCILE_AGE_MS = 30 * 60_000;

/** Resolve an uncertain create by asking the node whether it processed our request id. */
export async function reconcile(requestId: string): Promise<void> {
  const l = await loadRequest(requestId);
  if (!l || l.request.state !== "uncertain" || l.request.operation !== "create") return;
  const started = Date.now();
  const age = Date.now() - (l.request.startedAt ?? l.request.createdAt).getTime();
  let input: NormalizedAccountInput;
  try {
    input = decryptInput(l.request);
  } catch {
    await finalizeFailure(l, "OUTCOME_UNKNOWN", "Request input could not be read.", started, { keepCapacity: true });
    return;
  }

  try {
    const { server, driver } = await getNodeDriver(l.server.id);
    const caps = server.capabilities ?? {};
    if (caps.lookupByRequestId) {
      const found = await driver.findAccountByRequestId(requestId);
      if (found) {
        await finalizeSuccess(l, found, input, started);
        return;
      }
    } else if (!caps.idempotency) {
      // Neither lookup nor idempotent create: retrying could create a duplicate account.
      await finalizeFailure(l, "OUTCOME_UNKNOWN", "Server cannot confirm the outcome of an interrupted request.", started, { keepCapacity: true });
      return;
    }
    // Not found (or the node deduplicates by request id): retrying with the SAME request id is safe.
    if (l.request.attempts < env().PROVISION_MAX_ATTEMPTS) {
      const [requeued] = await db()
        .update(provisioningRequests)
        .set({ state: "queued" })
        .where(and(eq(provisioningRequests.id, requestId), eq(provisioningRequests.state, "uncertain")))
        .returning({ id: provisioningRequests.id });
      if (requeued) await enqueueProvisioning({ type: "create", requestId }, { delayMs: 1_000 });
      return;
    }
    // Still unconfirmed after every attempt (in progress or timing out on the node): the account may
    // yet be created there, so this is an unknown outcome, not a definite failure.
    await finalizeFailure(l, "OUTCOME_UNKNOWN", l.request.errorMessage ?? "Server could not confirm the account.", started, { keepCapacity: true });
  } catch (e) {
    // Node still unreachable: keep the request uncertain and try again later, then give up safely.
    if (age > MAX_RECONCILE_AGE_MS) {
      await finalizeFailure(l, "OUTCOME_UNKNOWN", "Server unreachable while confirming the account.", started, { keepCapacity: true });
      return;
    }
    logger.warn("reconcile failed; will retry", { requestId, ...errorSummary(e) });
    await enqueueProvisioning({ type: "reconcile", requestId }, { delayMs: 60_000 });
  }
}

async function finalizeSuccess(l: LoadedRequest, nodeAccount: NodeAccount, input: NormalizedAccountInput, started: number) {
  const adapter = getAdapter(l.def.adapterKey);
  let presented: PresentedAccount;
  let metadata: ReturnType<typeof safeMetadata>;
  let expiresAt: Date;
  let username: string | undefined;
  try {
    const provisioned = adapter.parseAccount(nodeAccount, adapterContext(l), input);
    presented = presentAccount(l.def, provisioned, { id: l.server.id, name: l.server.name });
    metadata = safeMetadata(l.def, provisioned);
    expiresAt = provisioned.expiresAt;
    username = provisioned.username;
  } catch (e) {
    const message = e instanceof AdapterResponseError ? e.message : "Unreadable account data from server.";
    // The node created something we cannot present: undo it on the node (best effort).
    try {
      const { driver } = await getNodeDriver(l.server.id);
      await driver.revokeAccount(nodeAccount.accountId, randomUUID());
    } catch (revokeError) {
      logger.error("compensating revoke failed", { requestId: l.request.id, ...errorSummary(revokeError) });
    }
    await finalizeFailure(l, "INVALID_NODE_RESPONSE", message, started);
    return;
  }

  const ttl = env().PROVISION_RESULT_TTL_SECONDS;
  await db().transaction(async (tx) => {
    await tx
      .update(vpnAccounts)
      .set({
        status: "active",
        remoteAccountId: nodeAccount.accountId,
        username: username ?? l.account.username,
        activatedAt: new Date(),
        expiresAt,
        metadata,
        failureCode: null,
        failureMessage: null,
      })
      .where(eq(vpnAccounts.id, l.account.id));
    await tx
      .update(provisioningRequests)
      .set({
        state: "succeeded",
        completedAt: new Date(),
        inputEncrypted: null,
        errorCode: null,
        errorMessage: null,
        resultEncrypted: encryptSecret(JSON.stringify(presented), EncryptionContext.provisioningResult(l.request.id)),
        resultExpiresAt: new Date(Date.now() + ttl * 1000),
      })
      .where(eq(provisioningRequests.id, l.request.id));
    await tx
      .update(servers)
      .set({ lastSeenAt: new Date(), lastSuccessfulConnectionAt: new Date() })
      .where(eq(servers.id, l.server.id));
  });
  await logEvent({
    event: "account.created",
    status: "success",
    serverId: l.server.id,
    protocolId: l.def.id,
    accountId: l.account.id,
    requestId: l.request.id,
    message: `${l.def.name} account created on ${l.server.name}${username ? ` for ${username}` : ""}${nodeAccount.replayed ? " (replayed)" : ""}.`,
    details: { remoteAccountId: nodeAccount.accountId, expiresAt: expiresAt.toISOString() },
    durationMs: Date.now() - started,
  });
}

async function finalizeFailure(
  l: LoadedRequest,
  code: string,
  safeMessage: string,
  started: number,
  opts: { keepCapacity?: boolean } = {},
) {
  const userMessage = USER_MESSAGES[code] ?? DEFAULT_USER_MESSAGE;
  await db().transaction(async (tx) => {
    await tx
      .update(vpnAccounts)
      .set({
        status: "failed",
        failureCode: code,
        failureMessage: safeMessage.slice(0, 500),
        // An unknown outcome keeps its slot until the account would have expired; the expiry job
        // then frees the slot and removes the account from the server if it was created after all.
        ...(opts.keepCapacity ? { expiresAt: sql`${vpnAccounts.createdAt} + ${l.account.durationDays} * interval '1 day'` } : {}),
      })
      .where(eq(vpnAccounts.id, l.account.id));
    await tx
      .update(provisioningRequests)
      .set({ state: "failed", completedAt: new Date(), inputEncrypted: null, errorCode: code, errorMessage: userMessage })
      .where(eq(provisioningRequests.id, l.request.id));
    // A definite failure gives the slot and the creation-quota slot back; an unknown outcome keeps both.
    if (!opts.keepCapacity) await releaseCapacity(tx, l.account.id, { refundQuota: true });
  });
  await logEvent({
    event: "account.failed",
    status: "failure",
    level: "error",
    serverId: l.server.id,
    protocolId: l.def.id,
    accountId: l.account.id,
    requestId: l.request.id,
    message: `${l.def.name} account failed on ${l.server.name}: ${safeMessage}`,
    details: { code, capacityHeld: !!opts.keepCapacity },
    durationMs: Date.now() - started,
  });
}

// ---------------------------------------------------------------------------
// 3. Result retrieval (polling by the requester)
// ---------------------------------------------------------------------------

export type RequestStatus =
  | { status: "pending" }
  | { status: "failed"; error: { code: string; message: string } }
  | { status: "active"; account: PresentedAccount | null };

export async function getRequestStatus(requestId: string, claimToken: string): Promise<RequestStatus | null> {
  return (await getRequestResult(requestId, claimToken))?.status ?? null;
}

/** getRequestStatus plus the account id (for the account's avatar). Null for unknown ids or a wrong token. */
export async function getRequestResult(requestId: string, claimToken: string): Promise<{ status: RequestStatus; accountId: string | null } | null> {
  if (!/^[0-9a-f-]{36}$/.test(requestId) || !/^[0-9a-f]{64}$/.test(claimToken)) return null;
  const [r] = await db().select().from(provisioningRequests).where(eq(provisioningRequests.id, requestId)).limit(1);
  if (!r?.claimTokenHash || r.operation !== "create" || !safeEqual(r.claimTokenHash, sha256Hex(claimToken))) return null;
  const accountId = r.accountId;
  if (r.state === "failed") {
    return { accountId, status: { status: "failed", error: { code: r.errorCode ?? "FAILED", message: r.errorMessage ?? DEFAULT_USER_MESSAGE } } };
  }
  if (r.state !== "succeeded") return { accountId, status: { status: "pending" } };
  if (!r.resultEncrypted || !r.resultExpiresAt || r.resultExpiresAt < new Date()) return { accountId, status: { status: "active", account: null } };
  return {
    accountId,
    status: {
      status: "active",
      account: JSON.parse(decryptSecret(r.resultEncrypted, EncryptionContext.provisioningResult(r.id))) as PresentedAccount,
    },
  };
}

// ---------------------------------------------------------------------------
// 4. Revoke (predefined operation; admin UI arrives with account management)
// ---------------------------------------------------------------------------

export async function revokeAccount(accountId: string, actor: AuditActor): Promise<void> {
  const [acc] = await db().select().from(vpnAccounts).where(eq(vpnAccounts.id, accountId)).limit(1);
  if (!acc || acc.status !== "active" || !acc.remoteAccountId) throw new Error("Only active accounts can be revoked.");
  const { driver, server } = await getNodeDriver(acc.serverId);
  await driver.revokeAccount(acc.remoteAccountId, randomUUID());
  await db().transaction(async (tx) => {
    await tx.update(vpnAccounts).set({ status: "revoked", revokedAt: new Date(), revokedBy: actor.adminId }).where(eq(vpnAccounts.id, accountId));
    await releaseCapacity(tx, accountId);
  });
  await logEvent({
    event: "account.revoked",
    status: "success",
    serverId: acc.serverId,
    protocolId: acc.protocolId,
    accountId,
    adminId: actor.adminId,
    message: `Account ${acc.username ?? acc.remoteAccountId} revoked on ${server.name}.`,
  });
  await audit(actor, "account.revoke", { targetType: "account", targetId: accountId });
}

// ---------------------------------------------------------------------------
// 5. Sweeper (runs every minute in the worker)
// ---------------------------------------------------------------------------

export async function sweep(): Promise<{ requeued: number; reconciling: number; erased: number }> {
  const now = Date.now();
  const stuckQueued = await db()
    .select({ id: provisioningRequests.id, attempts: provisioningRequests.attempts })
    .from(provisioningRequests)
    .where(
      and(
        eq(provisioningRequests.operation, "create"),
        eq(provisioningRequests.state, "queued"),
        lt(provisioningRequests.updatedAt, new Date(now - 120_000)),
      ),
    )
    .limit(100);
  for (const r of stuckQueued) await enqueueProvisioning({ type: "create", requestId: r.id });

  const stalled = await db()
    .update(provisioningRequests)
    .set({ state: "uncertain", errorCode: "WORKER_INTERRUPTED", errorMessage: "Worker stopped while the request was in flight." })
    .where(
      and(
        eq(provisioningRequests.operation, "create"),
        eq(provisioningRequests.state, "in_flight"),
        lt(provisioningRequests.updatedAt, new Date(now - env().NODE_PROVISION_TIMEOUT_MS - 60_000)),
      ),
    )
    .returning({ id: provisioningRequests.id });
  const uncertain = await db()
    .select({ id: provisioningRequests.id })
    .from(provisioningRequests)
    .where(
      and(
        eq(provisioningRequests.operation, "create"),
        eq(provisioningRequests.state, "uncertain"),
        lt(provisioningRequests.updatedAt, new Date(now - 120_000)),
      ),
    )
    .limit(100);
  const toReconcile = [...new Set([...stalled, ...uncertain].map((r) => r.id))];
  for (const id of toReconcile) await enqueueProvisioning({ type: "reconcile", requestId: id });

  const erased = await db()
    .update(provisioningRequests)
    .set({ resultEncrypted: null })
    .where(and(isNotNull(provisioningRequests.resultEncrypted), lt(provisioningRequests.resultExpiresAt, new Date(now))))
    .returning({ id: provisioningRequests.id });

  return { requeued: stuckQueued.length, reconciling: toReconcile.length, erased: erased.length };
}

