// 1. Request (API / server action) — synchronous part
// ---------------------------------------------------------------------------

export async function requestAccount(p: AccountRequestParams): Promise<AccountRequestResult> {
  if (!IDEMPOTENCY_KEY.test(p.idempotencyKey)) {
    throw new ProvisioningError("INVALID_IDEMPOTENCY_KEY", "Invalid request. Please reload the page and try again.", 400);
  }
  const loaded = await getProtocolWithFields({ slug: p.protocolSlug });
  if (!loaded || !loaded.protocol.enabled) throw new ProvisioningError("PROTOCOL_NOT_FOUND", "This protocol is not available.", 404);
  const def = loaded.definition;
  const adapter = getAdapter(def.adapterKey);

  // VALIDATE INPUT
  const parsed = buildInputSchema(def, adapter).safeParse(p.input);
  if (!parsed.success) {
    throw new ProvisioningError("VALIDATION_FAILED", "Please correct the highlighted fields.", 422, zodFieldErrors(parsed.error.issues));
  }
  const input = toNormalizedInput(parsed.data as Record<string, unknown>, def);
  const digest = sha256Hex(
    stableStringify({ serverId: p.serverId, protocol: def.slug, username: input.username, durationDays: input.durationDays, options: input.options }),
  );
  const idempotencyKey = `create:${p.idempotencyKey}`;
  const claimToken = claimTokenFor(p.idempotencyKey);

  // IDEMPOTENCY (a double-click returns the original request)
  const existing = await findByIdempotencyKey(idempotencyKey);
  if (existing) return replay(existing, digest, claimToken);

  // RATE LIMIT. The burst limit counts every attempt; the daily limit is only checked here and
  // counted once the request is accepted, so refused attempts (full, offline...) do not use it up.
  const ipHash = hashClientIp(p.clientIp);
  const dailyKey = `prov:day:${ipHash ?? "unknown"}:${def.id}`;
  if (!p.actor) {
    const [burst, daily] = await Promise.all([
      rateLimit(`prov:burst:${ipHash ?? "unknown"}`, 5, 60, "closed"),
      peekRateLimit(dailyKey, loaded.protocol.maxAccountsPerIpPerDay, 86_400, "closed"),
    ]);
    if (!burst.allowed || !daily.allowed) {
      throw new ProvisioningError(
        "RATE_LIMITED",
        !daily.allowed
          ? `You have reached today's limit of ${loaded.protocol.maxAccountsPerIpPerDay} ${def.name} account${loaded.protocol.maxAccountsPerIpPerDay === 1 ? "" : "s"}. Please try again tomorrow or choose another protocol.`
          : "Too many requests. Please wait a minute and try again.",
        429,
        undefined,
        {
          retryAfterSeconds: Math.max(!burst.allowed ? burst.resetSeconds : 0, !daily.allowed ? daily.resetSeconds : 0, 1),
          limitScope: !daily.allowed ? "daily" : "burst",
        },
      );
    }
  }
  const settings = await getSiteSettings();

  // CHECK SERVER / PROTOCOL / CAPACITY, CREATE PENDING RECORDS (one transaction, row locks)
  const requestId = randomUUID();
  let accountId: string;
  let window = quotaWindow(new Date(), settings.quota.resetTimes, settings.quota.timezone);
  try {
    accountId = await db().transaction(async (tx) => {
      const [server] = await tx.select().from(servers).where(eq(servers.id, p.serverId)).for("update");
      // Computed under the row lock, so requests are counted in the window they are serialised in.
      window = quotaWindow(new Date(), settings.quota.resetTimes, settings.quota.timezone);
      if (!server || server.deletedAt || server.lifecycle === "draft" || server.lifecycle === "disabled") {
        throw new ProvisioningError("SERVER_NOT_FOUND", "This server is not available.", 404);
      }
      if (server.lifecycle === "maintenance" || server.status === "maintenance") {
        throw new ProvisioningError("SERVER_UNAVAILABLE", "Server temporarily under maintenance.", 409);
      }
      if (server.status === "offline" || server.compatibility === "unsupported") {
        throw new ProvisioningError("SERVER_UNAVAILABLE", "This server is currently offline. Please choose another server.", 409);
      }
      const [sp] = await tx
        .select()
        .from(serverProtocols)
        .where(and(eq(serverProtocols.serverId, server.id), eq(serverProtocols.protocolId, def.id)))
        .for("update");
      if (!sp || !sp.enabled || !sp.detected || sp.serviceStatus === "stopped") {
        throw new ProvisioningError("PROTOCOL_UNAVAILABLE", `${def.name} is not available on this server.`, 409);
      }
      const reservation = await reserveCapacity(tx, server.id, sp.id, window);
      if (!reservation.ok) {
        if (reservation.reason === "quota_reached") {
          const resetsAt = reservation.resetsAt ?? window.end;
          throw new ProvisioningError(
            "QUOTA_REACHED",
            `All ${def.name} slots on this server are taken for now. New slots open at ${formatLocalTime(resetsAt, settings.quota.timezone)} (${settings.quota.timezone}).`,
            409,
            undefined,
            { resetsAt },
          );
        }
        throw new ProvisioningError(
          "CAPACITY_REACHED",
          reservation.reason === "protocol_full"
            ? `${def.name} is full on this server. Please choose another server.`
            : "This server is full. Please choose another server.",
          409,
        );
      }
      const [account] = await tx
        .insert(vpnAccounts)
        .values({
          serverId: server.id,
          protocolId: def.id,
          username: input.username ?? null,
          status: "pending",
          durationDays: input.durationDays,
          clientIpHash: ipHash,
          holdsCapacity: true,
          quotaWindowStart: reservation.quotaWindowStart,
        })
        .returning({ id: vpnAccounts.id });
      await tx.insert(provisioningRequests).values({
        id: requestId,
        idempotencyKey,
        operation: "create",
        state: "queued",
        accountId: account!.id,
        serverId: server.id,
        protocolId: def.id,
        inputDigest: digest,
        inputEncrypted: encryptSecret(JSON.stringify(input), EncryptionContext.provisioningInput(requestId)),
        claimTokenHash: sha256Hex(claimToken),
        clientIpHash: ipHash,
        requestedByAdminId: p.actor?.adminId ?? null,
      });
      await refreshServerStatus(tx, server.id);
      return account!.id;
    });
  } catch (e) {
    if (isUniqueViolation(e)) {
      const again = await findByIdempotencyKey(idempotencyKey);
      if (again) return replay(again, digest, claimToken);
    }
    throw e;
  }

  if (!p.actor) await countRateLimit(dailyKey, 86_400);

  await logEvent({
    event: "account.requested",
    status: "info",
    serverId: p.serverId,
    protocolId: def.id,
    accountId,
    requestId,
    adminId: p.actor?.adminId,
    message: `${def.name} account requested${input.username ? ` for ${input.username}` : ""}.`,
    details: { durationDays: input.durationDays, options: input.options },
  });
  if (p.actor) await audit(p.actor, "account.request", { targetType: "account", targetId: accountId, details: { protocol: def.slug } });

  // SEND TO QUEUE (if Redis is unavailable the sweeper picks the request up later)
  try {
    await enqueueProvisioning({ type: "create", requestId });
  } catch (e) {
    logger.error("failed to enqueue provisioning job", { requestId, ...errorSummary(e) });
  }
  return { requestId, claimToken, state: "queued", replayed: false };
}

async function findByIdempotencyKey(key: string) {
  const [r] = await db().select().from(provisioningRequests).where(eq(provisioningRequests.idempotencyKey, key)).limit(1);
  return r ?? null;
}

function replay(existing: ProvisioningRequest, digest: string, claimToken: string): AccountRequestResult {
  if (existing.inputDigest !== digest) {
    throw new ProvisioningError("IDEMPOTENCY_CONFLICT", "This request was already submitted with different details. Reload the page to start again.", 409);
  }
  return { requestId: existing.id, claimToken, state: existing.state, replayed: true };
}

